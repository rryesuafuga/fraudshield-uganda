/// Officer statistics for risk analysis
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct OfficerStats {
    pub officer_id: String,
    pub name: String,
    pub loan_count: u32,
    pub total_amount: f64,
    pub alert_count: u32,
    pub z_score: f64,
    pub risk_score: u32,
}

/// Column mapping detection result
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ColumnMapping {
    pub original_column: String,
    pub mapped_field: Option<String>,
    pub confidence: u32,
    pub detection_method: String,
}

/// Analysis summary statistics
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct AnalysisSummary {
    pub total_records: u32,
    pub critical_alerts: u32,
    pub high_alerts: u32,
    pub medium_alerts: u32,
    pub low_alerts: u32,
    pub risk_score: u32,
}

/// Complete analysis results
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AnalysisResults {
    pub summary: AnalysisSummary,
    pub alerts: Vec<FraudAlert>,
    pub officers: Vec<OfficerStats>,
}

