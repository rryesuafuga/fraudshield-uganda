fn detect_ghost_loans(data: &[LoanRecord], alerts: &mut Vec<FraudAlert>) {
    let mut phone_counts: HashMap<String, Vec<&LoanRecord>> = HashMap::new();

    for record in data {
        if let Some(ref phone) = record.phone {
            if !phone.is_empty() {
                phone_counts.entry(phone.clone()).or_default().push(record);
            }
        }
    }

    for (phone, records) in phone_counts {
        if records.len() > 1 {
            let total_amount: f64 = records.iter()
                .filter_map(|r| r.amount)
                .sum();

            let loan_ids: Vec<String> = records.iter()
                .filter_map(|r| r.loan_id.clone())
                .collect();

            let details: Vec<serde_json::Value> = records.iter()
                .map(|r| serde_json::json!({
                    "loan_id": r.loan_id,
                    "borrower": r.borrower_name,
                    "amount": r.amount
                }))
                .collect();

            alerts.push(FraudAlert {
                alert_type: "GHOST_LOAN".to_string(),
                severity: if records.len() >= 4 { "CRITICAL".to_string() } else { "HIGH".to_string() },
                title: "Duplicate Phone Number Detected".to_string(),
                description: format!("Phone {} appears in {} different loans", phone, records.len()),
                amount_at_risk: total_amount,
                officer_id: records.first().and_then(|r| r.officer_id.clone()),
                loan_ids,
                details: serde_json::json!(details),
            });
        }
    }
}

fn detect_loan_stacking(data: &[LoanRecord], alerts: &mut Vec<FraudAlert>) {
    let mut borrower_date_map: HashMap<String, Vec<&LoanRecord>> = HashMap::new();

    for record in data {
        if let (Some(ref borrower_id), Some(ref date)) = (&record.borrower_id, &record.loan_date) {
            let key = format!("{}-{}", borrower_id, date);
            borrower_date_map.entry(key).or_default().push(record);
        }
    }

    for (_, records) in borrower_date_map {
        if records.len() > 1 {
            let total_amount: f64 = records.iter()
                .filter_map(|r| r.amount)
                .sum();

            let loan_ids: Vec<String> = records.iter()
                .filter_map(|r| r.loan_id.clone())
                .collect();

            alerts.push(FraudAlert {
                alert_type: "LOAN_STACKING".to_string(),
                severity: "HIGH".to_string(),
                title: "Multiple Loans Same Day".to_string(),
                description: format!("Borrower received {} loans on same date, total UGX {:.0}",
                    records.len(), total_amount),
                amount_at_risk: total_amount,
                officer_id: records.first().and_then(|r| r.officer_id.clone()),
                loan_ids,
                details: serde_json::json!(records),
            });
        }
    }
}

fn detect_officer_anomalies(
    data: &[LoanRecord],
    alerts: &mut Vec<FraudAlert>,
    officer_stats: &mut HashMap<String, OfficerStats>
) {
    // Build officer statistics
    for record in data {
        let officer_id = record.officer_id.clone().unwrap_or_else(|| "Unknown".to_string());
        let officer_name = record.officer_name.clone().unwrap_or_else(|| officer_id.clone());
        let amount = record.amount.unwrap_or(0.0);

        let stats = officer_stats.entry(officer_id.clone()).or_insert(OfficerStats {
            officer_id: officer_id.clone(),
            name: officer_name,
            ..Default::default()
        });

        stats.loan_count += 1;
        stats.total_amount += amount;
    }

    // Calculate z-scores
    let counts: Vec<f64> = officer_stats.values().map(|s| s.loan_count as f64).collect();
    if counts.is_empty() {
        return;
    }

    let mean = counts.iter().sum::<f64>() / counts.len() as f64;
    let variance = counts.iter().map(|c| (c - mean).powi(2)).sum::<f64>() / counts.len() as f64;
    let std_dev = variance.sqrt();

    for stats in officer_stats.values_mut() {
        if std_dev > 0.0 {
            stats.z_score = (stats.loan_count as f64 - mean) / std_dev;
        }

        // Generate alert for anomalous officers
        if stats.z_score > 2.0 {
            alerts.push(FraudAlert {
                alert_type: "OFFICER_ANOMALY".to_string(),
                severity: if stats.z_score > 3.0 { "HIGH".to_string() } else { "MEDIUM".to_string() },
                title: "Unusual Officer Volume".to_string(),
                description: format!("Officer {} processed {} loans ({:.1} std from avg)",
                    stats.name, stats.loan_count, stats.z_score),
                amount_at_risk: stats.total_amount * 0.1,
                officer_id: Some(stats.officer_id.clone()),
                loan_ids: vec![],
                details: serde_json::json!({
                    "officer_name": stats.name,
                    "loan_count": stats.loan_count,
                    "z_score": stats.z_score
                }),
            });
        }
    }
}

fn detect_timing_anomalies(data: &[LoanRecord], alerts: &mut Vec<FraudAlert>) {
    for record in data {
        if let Some(ref time) = record.approval_time {
            if let Some(hour) = time.split(':').next().and_then(|h| h.parse::<u32>().ok()) {
                if hour < 6 || hour >= 22 {
                    alerts.push(FraudAlert {
                        alert_type: "TIMING_ANOMALY".to_string(),
                        severity: "MEDIUM".to_string(),
                        title: "After-Hours Approval".to_string(),
                        description: format!("Loan {} approved at {}",
                            record.loan_id.as_deref().unwrap_or("N/A"), time),
                        amount_at_risk: record.amount.unwrap_or(0.0),
                        officer_id: record.officer_id.clone(),
                        loan_ids: record.loan_id.clone().map(|id| vec![id]).unwrap_or_default(),
                        details: serde_json::json!(record),
                    });
                }
            }
        }
    }
}

fn detect_amount_anomalies(data: &[LoanRecord], alerts: &mut Vec<FraudAlert>) {
    let amounts: Vec<f64> = data.iter()
        .filter_map(|r| r.amount)
        .filter(|&a| a > 0.0)
        .collect();

    if amounts.len() < 5 {
        return;
    }

    let mean = amounts.iter().sum::<f64>() / amounts.len() as f64;
    let variance = amounts.iter().map(|a| (a - mean).powi(2)).sum::<f64>() / amounts.len() as f64;
    let std_dev = variance.sqrt();
    let threshold = mean + (2.5 * std_dev);

    for record in data {
        if let Some(amount) = record.amount {
            if amount > threshold {
                let percent_above = ((amount / mean - 1.0) * 100.0) as i32;
                alerts.push(FraudAlert {
                    alert_type: "AMOUNT_ANOMALY".to_string(),
                    severity: "MEDIUM".to_string(),
                    title: "Unusually Large Loan".to_string(),
                    description: format!("Loan amount UGX {:.0} is {}% above average", amount, percent_above),
                    amount_at_risk: amount,
                    officer_id: record.officer_id.clone(),
                    loan_ids: record.loan_id.clone().map(|id| vec![id]).unwrap_or_default(),
                    details: serde_json::json!({
                        "loan": record,
                        "mean": mean,
                        "std_dev": std_dev
                    }),
                });
            }
        }
    }
}

fn calculate_risk_score(alerts: &[FraudAlert]) -> u32 {
    let mut score: u32 = 0;

    for alert in alerts {
        match alert.severity.as_str() {
            "CRITICAL" => score += 25,
            "HIGH" => score += 15,
            "MEDIUM" => score += 8,
            _ => score += 3,
        }
    }

    score.min(100)
}

