/// Parse CSV data and return as JSON array
#[wasm_bindgen]
pub fn parse_csv(csv_content: &str) -> String {
    let mut records: Vec<HashMap<String, String>> = Vec::new();
    let mut lines = csv_content.lines();

    // Get headers from first line
    let headers: Vec<String> = match lines.next() {
        Some(header_line) => parse_csv_line(header_line),
        None => return "[]".to_string(),
    };

    // Parse data rows
    for line in lines {
        if line.trim().is_empty() {
            continue;
        }
        let values = parse_csv_line(line);
        let mut record: HashMap<String, String> = HashMap::new();

        for (i, header) in headers.iter().enumerate() {
            let value = values.get(i).cloned().unwrap_or_default();
            record.insert(header.clone(), value);
        }
        records.push(record);
    }

    serde_json::to_string(&records).unwrap_or_else(|_| "[]".to_string())
}

/// Detect column mappings from raw data JSON
#[wasm_bindgen]
pub fn detect_columns(raw_data_json: &str) -> String {
    let data: Vec<HashMap<String, serde_json::Value>> = match serde_json::from_str(raw_data_json) {
        Ok(d) => d,
        Err(_) => return "[]".to_string(),
    };

    if data.is_empty() {
        return "[]".to_string();
    }

    let columns: Vec<String> = data[0].keys().cloned().collect();
    let mut mappings: Vec<ColumnMapping> = Vec::new();
    let mut used_fields: std::collections::HashSet<String> = std::collections::HashSet::new();

    // Collect all potential mappings with scores
    let mut all_detections: Vec<(String, String, u32, String)> = Vec::new();

    for col in &columns {
        if let Some((field, confidence, method)) = detect_column_type(col, &data) {
            all_detections.push((col.clone(), field, confidence, method));
        }
    }

    // Sort by confidence descending
    all_detections.sort_by(|a, b| b.2.cmp(&a.2));

    // Assign mappings, avoiding duplicates
    for (col, field, confidence, method) in all_detections {
        if !used_fields.contains(&field) {
            mappings.push(ColumnMapping {
                original_column: col,
                mapped_field: Some(field.clone()),
                confidence,
                detection_method: method,
            });
            used_fields.insert(field);
        }
    }

    // Add unmapped columns
    for col in &columns {
        if !mappings.iter().any(|m| m.original_column == *col) {
            mappings.push(ColumnMapping {
                original_column: col.clone(),
                mapped_field: None,
                confidence: 0,
                detection_method: "none".to_string(),
            });
        }
    }

    serde_json::to_string(&mappings).unwrap_or_else(|_| "[]".to_string())
}

/// Run fraud analysis on mapped data
#[wasm_bindgen]
pub fn analyze_fraud(mapped_data_json: &str) -> String {
    let data: Vec<LoanRecord> = match serde_json::from_str(mapped_data_json) {
        Ok(d) => d,
        Err(_) => return "{\"error\": \"Failed to parse data\"}".to_string(),
    };

    if data.is_empty() {
        return "{\"error\": \"No data to analyze\"}".to_string();
    }

    let mut alerts: Vec<FraudAlert> = Vec::new();
    let mut officer_stats: HashMap<String, OfficerStats> = HashMap::new();

    // Run detection algorithms
    detect_ghost_loans(&data, &mut alerts);
    detect_loan_stacking(&data, &mut alerts);
    detect_officer_anomalies(&data, &mut alerts, &mut officer_stats);
    detect_timing_anomalies(&data, &mut alerts);
    detect_amount_anomalies(&data, &mut alerts);

    // Calculate summary
    let mut summary = AnalysisSummary {
        total_records: data.len() as u32,
        ..Default::default()
    };

    for alert in &alerts {
        match alert.severity.as_str() {
            "CRITICAL" => summary.critical_alerts += 1,
            "HIGH" => summary.high_alerts += 1,
            "MEDIUM" => summary.medium_alerts += 1,
            _ => summary.low_alerts += 1,
        }

        // Track officer involvement
        if let Some(ref officer_id) = alert.officer_id {
            if let Some(stats) = officer_stats.get_mut(officer_id) {
                stats.alert_count += 1;
            }
        }
    }

    // Calculate risk score
    summary.risk_score = calculate_risk_score(&alerts);

    // Calculate officer risk scores
    let mut officers: Vec<OfficerStats> = officer_stats.into_values().collect();
    for officer in &mut officers {
        officer.risk_score = ((officer.alert_count * 10) as f64 +
            if officer.z_score > 2.0 { 30.0 } else { 0.0 }).min(100.0) as u32;
    }
    officers.sort_by(|a, b| b.risk_score.cmp(&a.risk_score));

    let results = AnalysisResults {
        summary,
        alerts,
        officers,
    };

    serde_json::to_string(&results).unwrap_or_else(|_| "{\"error\": \"Serialization failed\"}".to_string())
}

/// Generate sample data for testing
#[wasm_bindgen]
pub fn generate_sample_data(num_loans: u32) -> String {
    let first_names = ["John", "Mary", "Peter", "Grace", "David", "Sarah", "James", "Agnes", "Robert", "Florence"];
    let last_names = ["Mukasa", "Nakato", "Ssemakula", "Nambi", "Okello", "Akello", "Wasswa", "Babirye", "Kato", "Nalongo"];
    let officers = ["OFF001", "OFF002", "OFF003", "OFF004", "OFF005"];
    let branches = ["Kampala Central", "Entebbe", "Jinja", "Mbarara", "Gulu"];
    let statuses = ["active", "active", "active", "completed", "defaulted"];

    // Simple pseudo-random generator (for deterministic results)
    let mut seed: u64 = 12345;
    let mut rng = || -> f64 {
        seed = seed.wrapping_mul(1103515245).wrapping_add(12345);
        ((seed >> 16) & 0x7fff) as f64 / 32768.0
    };

    // Create fraud phone numbers
    let mut fraud_phones: Vec<String> = Vec::new();
    for _ in 0..5 {
        let phone = format!("07{}", (rng() * 90000000.0 + 10000000.0) as u64);
        fraud_phones.push(phone);
    }

    let mut records: Vec<HashMap<String, serde_json::Value>> = Vec::new();

    for i in 0..num_loans {
        let is_fraud = rng() < 0.05;
        let is_ghost = is_fraud && rng() < 0.5;
        let is_stacking = is_fraud && !is_ghost && rng() < 0.5;

        let hour = if is_fraud && !is_ghost && !is_stacking {
            if rng() < 0.5 {
                (rng() * 5.0) as u32
            } else {
                22 + (rng() * 3.0) as u32
            }
        } else {
            8 + (rng() * 10.0) as u32
        };

        let first_name = first_names[(rng() * first_names.len() as f64) as usize];
        let last_name = last_names[(rng() * last_names.len() as f64) as usize];

        let phone = if is_ghost {
            fraud_phones[(rng() * fraud_phones.len() as f64) as usize].clone()
        } else {
            format!("07{}", (rng() * 90000000.0 + 10000000.0) as u64)
        };

        let borrower_id = if is_stacking {
            format!("MBR{:04}", i / 3)
        } else {
            format!("MBR{:04}", i + 1)
        };

        let officer_id = if is_fraud {
            officers[0].to_string()
        } else {
            officers[(rng() * officers.len() as f64) as usize].to_string()
        };

        let month = (rng() * 12.0) as u32 + 1;
        let day = (rng() * 28.0) as u32 + 1;

        let mut record: HashMap<String, serde_json::Value> = HashMap::new();
        record.insert("loan_id".to_string(), serde_json::json!(format!("LN{:05}", i + 1)));
        record.insert("borrower_id".to_string(), serde_json::json!(borrower_id));
        record.insert("borrower_name".to_string(), serde_json::json!(format!("{} {}", first_name, last_name)));
        record.insert("phone".to_string(), serde_json::json!(phone));
        record.insert("amount".to_string(), serde_json::json!((rng() * 4000000.0 + 500000.0) as u64));
        record.insert("loan_date".to_string(), serde_json::json!(format!("2024-{:02}-{:02}", month, day)));
        record.insert("approval_time".to_string(), serde_json::json!(format!("{:02}:{:02}", hour, (rng() * 60.0) as u32)));
        record.insert("officer_id".to_string(), serde_json::json!(officer_id));
        record.insert("branch".to_string(), serde_json::json!(branches[(rng() * branches.len() as f64) as usize]));
        record.insert("status".to_string(), serde_json::json!(statuses[(rng() * statuses.len() as f64) as usize]));

        records.push(record);
    }

    serde_json::to_string(&records).unwrap_or_else(|_| "[]".to_string())
}

