fn detect_column_type(col_name: &str, data: &[HashMap<String, serde_json::Value>]) -> Option<(String, u32, String)> {
    let col_lower = col_name.to_lowercase().replace(|c: char| !c.is_alphanumeric(), "_");
    let variations = get_name_variations();

    // Get sample values
    let sample: Vec<String> = data.iter()
        .take(100)
        .filter_map(|row| row.get(col_name))
        .filter_map(|v| match v {
            serde_json::Value::String(s) => Some(s.clone()),
            serde_json::Value::Number(n) => Some(n.to_string()),
            _ => None,
        })
        .filter(|s| !s.is_empty())
        .collect();

    let mut best_match: Option<String> = None;
    let mut best_score: u32 = 0;
    let mut detection_method = "none".to_string();

    // Method 1: Name matching
    for (field, vars) in &variations {
        for var in vars {
            // Exact match
            if col_lower == *var {
                return Some((field.to_string(), 100, "exact_match".to_string()));
            }

            // Contains match
            if col_lower.contains(var) || var.contains(&col_lower.as_str()) {
                let score = 85;
                if score > best_score {
                    best_score = score;
                    best_match = Some(field.to_string());
                    detection_method = "name_match".to_string();
                }
            }

            // Fuzzy match
            let similarity = levenshtein_similarity(&col_lower, var);
            if similarity > 0.7 {
                let score = (similarity * 100.0) as u32;
                if score > best_score {
                    best_score = score;
                    best_match = Some(field.to_string());
                    detection_method = "fuzzy_match".to_string();
                }
            }
        }
    }

    // Method 2: Pattern detection
    if !sample.is_empty() {
        if let Some((field, confidence)) = detect_by_pattern(&sample) {
            if confidence > best_score {
                best_score = confidence;
                best_match = Some(field);
                detection_method = "pattern".to_string();
            }
        }
    }

    // Method 3: Statistical detection
    if best_match.is_none() && !sample.is_empty() {
        if let Some((field, confidence)) = detect_by_statistics(&sample) {
            if confidence > best_score {
                best_score = confidence;
                best_match = Some(field);
                detection_method = "statistics".to_string();
            }
        }
    }

    if best_score > 40 {
        best_match.map(|field| (field, best_score, detection_method))
    } else {
        None
    }
}

fn detect_by_pattern(sample: &[String]) -> Option<(String, u32)> {
    // Phone number patterns
    let phone_regex = Regex::new(r"^(\+?256|0)?[0-9]{9}$").ok()?;
    let phone_matches = sample.iter()
        .filter(|s| phone_regex.is_match(&s.replace([' ', '-', '(', ')'], "")))
        .count();
    if phone_matches as f64 / sample.len() as f64 > 0.7 {
        return Some(("phone".to_string(), 90));
    }

    // National ID patterns (Uganda NIN)
    let nin_regex = Regex::new(r"^[A-Z]{2}\d{13}[A-Z0-9]$").ok()?;
    let nin_matches = sample.iter()
        .filter(|s| nin_regex.is_match(&s.to_uppercase().replace([' ', '-'], "")))
        .count();
    if nin_matches as f64 / sample.len() as f64 > 0.7 {
        return Some(("national_id".to_string(), 92));
    }

    // Date patterns
    let date_regex = Regex::new(r"^\d{4}-\d{2}-\d{2}$|^\d{2}/\d{2}/\d{4}$").ok()?;
    let date_matches = sample.iter()
        .filter(|s| date_regex.is_match(s))
        .count();
    if date_matches as f64 / sample.len() as f64 > 0.7 {
        return Some(("loan_date".to_string(), 85));
    }

    // Time patterns
    let time_regex = Regex::new(r"^\d{2}:\d{2}(:\d{2})?$").ok()?;
    let time_matches = sample.iter()
        .filter(|s| time_regex.is_match(s))
        .count();
    if time_matches as f64 / sample.len() as f64 > 0.7 {
        return Some(("approval_time".to_string(), 80));
    }

    // Amount patterns (formatted numbers with commas)
    let amount_regex = Regex::new(r"^\d{1,3}(,\d{3})+(\.\d{2})?$").ok()?;
    let amount_matches = sample.iter()
        .filter(|s| amount_regex.is_match(s))
        .count();
    if amount_matches as f64 / sample.len() as f64 > 0.7 {
        return Some(("amount".to_string(), 85));
    }

    None
}

fn detect_by_statistics(sample: &[String]) -> Option<(String, u32)> {
    // Check if numeric
    let numeric_sample: Vec<f64> = sample.iter()
        .filter_map(|s| s.replace(',', "").parse::<f64>().ok())
        .collect();

    if numeric_sample.len() as f64 / sample.len() as f64 > 0.9 {
        let mean = numeric_sample.iter().sum::<f64>() / numeric_sample.len() as f64;
        let min = numeric_sample.iter().cloned().fold(f64::INFINITY, f64::min);
        let max = numeric_sample.iter().cloned().fold(f64::NEG_INFINITY, f64::max);

        // Amount detection: large positive numbers
        if min >= 0.0 && mean > 100000.0 {
            return Some(("amount".to_string(), 75));
        }

        // Interest rate: 0-100 range
        if min >= 0.0 && max <= 100.0 && mean < 50.0 {
            return Some(("interest_rate".to_string(), 60));
        }

        // Term months: small positive integers
        if min >= 1.0 && max <= 360.0 {
            return Some(("term_months".to_string(), 55));
        }
    }

    // Check for unique IDs
    let unique: std::collections::HashSet<&String> = sample.iter().collect();
    if unique.len() as f64 / sample.len() as f64 > 0.95 {
        if sample.get(0).map(|s| s.len()).unwrap_or(0) < 15 {
            return Some(("loan_id".to_string(), 60));
        }
    }

    // Check for names (2+ words, mostly alphabetic)
    let name_regex = Regex::new(r"^[A-Za-z]+\s+[A-Za-z]+").ok()?;
    let name_matches = sample.iter()
        .filter(|s| name_regex.is_match(s))
        .count();
    if name_matches as f64 / sample.len() as f64 > 0.7 {
        return Some(("borrower_name".to_string(), 70));
    }

    // Check for status keywords
    let status_keywords = ["active", "inactive", "paid", "closed", "pending",
        "approved", "rejected", "defaulted", "completed", "disbursed", "overdue"];
    let status_matches = sample.iter()
        .filter(|s| status_keywords.iter().any(|k| s.to_lowercase().contains(k)))
        .count();
    if status_matches as f64 / sample.len() as f64 > 0.5 {
        return Some(("status".to_string(), 80));
    }

    None
}

